'"test":[{"q":"Кто ввёл слово «философия»?","options":["Сократ","Пифагор","Платон","Аристотель"],"correct":[1]}]}]}\n';

  function build(o) {
    o = cfg(o);
    var p = head(o) + '\n' + split(o) + '\n' + what(o) + '\n' + HOW_TEXT + '\n' + howQA(o) + '\n' + LOOK + '\n' +
      (o.fmt === 'json' ? FORMAT_JSON + '\n' + EXAMPLE_JSON : FORMAT_MARKUP + '\n' + EXAMPLE_MARKUP) + '\n' +
      size(o) + '\n' + check(o) + '\n' +
      (o.fmt === 'json' ? 'Ответь ТОЛЬКО JSON-объектом — без вступления, пояснений и вопросов в конце.' : 'Ответь ТОЛЬКО конспектом в этом формате — без вступления, пояснений и вопросов в конце.');
    if (o.test && o.testSrc !== 'ai' && String(o.bank || '').trim()) p += '\n\n=== МОЯ БАЗА ТЕСТОВ ===\n' + String(o.bank).trim() + '\n=== КОНЕЦ БАЗЫ ===';
    return p;
  }

  /* ---------- «Доработать»: короткие промты в тот же чат ---------- */
  function improve(kind, lec, o) {
    o = cfg(o); var n = N[o.depth] || N.medium, L = lec ? lec.label + '. ' + lec.title : '';
    var js = o.fmt === 'json';
    var only = function (sec, what2) {
      return js
        ? 'Пришли JSON-объект {"format":"studyplay-notes","lectures":[{"title":"' + L + '", ' + what2 + '}]} — только с этим разделом, по тем же правилам. Ответь только JSON.'
        : 'Ответь только этим кусочком в том же формате: первая строка «## ' + L + '», затем «### ' + sec + '» и содержимое. Больше ничего не пиши.';
    };
    switch (kind) {
      case 'test': return 'Для «' + L + '» сделай тест на ' + n.test + ' вопросов по правилам из первого сообщения (4 варианта, верные отмечены, неверные правдоподобные, ключ проверен по материалу). ' + only('Тест', '"test": [ … ]');
      case 'qs': return 'Для «' + L + '» пришли раздел вопросов целиком заново: ' + n.qs + ' вопросов с ответами (ответ начинается с «**Коротко:**»), у каждого — где это в конспекте (точный подзаголовок). ' + only('Вопросы', '"questions": [ … ]');
      case 'where': return 'В «' + L + '» у вопросов не указано, где ответ в конспекте. Пришли раздел вопросов заново целиком, теми же вопросами, и у каждого добавь «@ Где: <точный подзаголовок из конспекта>». ' + only('Вопросы', '"questions": [ … с полем "where" ]');
      case 'cards': return 'Для «' + L + '» сделай ' + n.cards + ' карточек для запоминания (одна карточка — один факт, ответ до 15 слов, без повторов вопросов). ' + only('Карточки', '"cards": [ … ]');
      case 'tasks': return 'Для «' + L + '» сделай ' + n.tasks + ' задач с подробным решением по шагам и ответом. ' + only('Задачи', '"tasks": [ … ]');
      case 'sum': return 'Для «' + L + '» напиши раздел «Главное»: ' + n.sum + ' коротких пунктов — самое важное. ' + only('Главное', '"summary": [ … ]');
      case 'text': return 'Конспект «' + L + '» получился слишком коротким. Перепиши его ' + (o.depth === 'short' ? 'полнее' : 'подробно') + ': ' + n.parts + ' частей с подзаголовками, первая — «Суть простыми словами», в каждой определение → объяснение → пример, таблицы и схемы где уместно, «> Запомни:» и «> Ловушка:». Ничего важного из материала не пропускай. ' +
        (js ? 'Пришли JSON-объект {"format":"studyplay-notes","lectures":[{"title":"' + L + '", "text": "…"}]} — только с полем "text". Ответь только JSON.' : 'Ответь только этим кусочком: первая строка «## ' + L + '», затем «### Конспект» и весь текст. Больше ничего не пиши.');
      default: return 'Проверь весь конспект по чек-листу из первого сообщения (полнота материала, «Суть простыми словами», ответы с «Коротко», «@ Где:», верные ответы теста, формат) и пришли исправленную версию целиком, в том же формате, без пояснений.';
    }
  }

  SP.NOTES_PROMPTS = { build: build, improve: improve, defaults: DEF, counts: N,
    /* для совместимости со старым кодом */
    markup: build({ fmt: 'markup' }), json: build({ fmt: 'json' }) };
