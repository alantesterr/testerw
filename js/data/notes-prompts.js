/* =====================================================================
   ПРОМТЫ ДЛЯ ИИ — ПО ШАГАМ (конструктор конспекта, mynotes.js).
   Каждый шаг — короткий промт про одно дело: так бесплатные модели (ChatGPT, Gemini,
   DeepSeek, Qwen, Copilot) делают каждую часть максимально хорошо.
     1) konspekt — только сам конспект: «Главное», текст с подзаголовками, термины;
     2) qs — вопросы;  3) test — тест;  4) cards — карточки;  5) tasks — задачи;
        all — всё из 2–5 одним промтом (для тех, кому лень по шагам);
     fix — переделать одну лекцию по пожеланию студента.
   Любая настройка может быть «ai» (ИИ решит сам) или «self» (студент напишет в чате сам).
   Пожелания студента в чате всегда важнее настроек — это сказано в каждом промте.
   Шаги 2–5 пишутся «по конспекту выше» в том же чате и повторяют точные заголовки лекций —
   по ним сайт сам добавляет ответ в нужную лекцию. Ответ читает mynotes-format.js.
   ===================================================================== */
(function () {
  'use strict';
  var SP = window.SP;

  var DEF = { depth: 'ai', lang: 'auto', split: 'auto', nQs: 'ai', nTest: 'ai', nCards: 'ai', nTasks: 'ai', testSrc: 'ai', bank: '', withKonspekt: false };
  var DEPTH = {
    ai: 'реши сам по материалу: чтобы ничего важного для экзамена не пропало, но без воды.',
    self: 'как я напишу в сообщении; если не написал — реши сам: всё важное для экзамена, без воды.',
    short: 'КРАТКО — только то, что нужно для сдачи: определения, ключевые факты, классификации, схемы. 3–5 частей.',
    medium: 'СРЕДНЕ — всё важное из материала с понятными объяснениями и примерами, без воды. 4–8 частей.',
    full: 'ПОДРОБНО — весь материал, с объяснениями, примерами, разбором сложных мест и связями между темами. 6–12 частей. Ничего не сокращай.'
  };
  var LANG = {
    auto: 'Язык — язык материала (русский или казахский).',
    ru: 'Язык — русский (если материал на другом языке, переведи).',
    kk: 'Язык — казахский (если материал на другом языке, переведи). Служебные заголовки (### Главное, ### Конспект и т. п.) оставь как в формате.'
  };
  var SPLIT = {
    auto: 'Если в материале есть лекции — сохрани их, каждая «## Лекция N. Название». Если это сплошной текст, учебник или просто тема — раздели на темы «## Тема N. Название».',
    lectures: 'Сохрани деление на лекции как в материале: каждая — «## Лекция N. Название».',
    topics: 'Раздели материал на логичные темы (даже если в источнике по-другому): каждая — «## Тема N. Название».'
  };
  var WISH = 'Если в моём сообщении есть свои пожелания (объём, количество, язык, на что сделать упор, образец) — они важнее правил ниже.';
  var ONLY = 'Ответь только этим текстом в формате выше — без вступления, пояснений и вопросов в конце.';
  var LONG = 'Если ответ вот-вот оборвётся — закончи текущий кусок и последней строкой напиши: ПРОДОЛЖЕНИЕ СЛЕДУЕТ. Я напишу «дальше» — продолжи с того же места, не повторяя написанное.';

  function cfg(o) { return Object.assign({}, DEF, o || {}); }
  /* сколько: число, «реши сам» или «как я напишу» */
  function how(n, what, typical) {
    if (n === 'self') return 'столько, сколько я напишу в сообщении (если не написал — обычно ' + typical + ' ' + what + ')';
    if (n === 'ai' || !n) return 'столько, чтобы покрыть всё важное (обычно ' + typical + ' ' + what + ')';
    return n + ' ' + what;
  }
  /* список лекций, как они уже названы в конспекте — ИИ должен повторить заголовки слово в слово */
  function heads(lecs) {
    if (!lecs || !lecs.length) return 'для каждой лекции (темы) из конспекта выше';
    return 'для каждой лекции (темы) из конспекта. Заголовки повтори точно так:\n' + lecs.map(function (l) { return '## ' + l.label + '. ' + l.title; }).join('\n');
  }
  function context(o, ctx) {
    return o.withKonspekt && ctx && ctx.konspekt ? '\n\nВОТ КОНСПЕКТ (опирайся только на него и на материал лекции):\n<<<\n' + ctx.konspekt + '\n>>>' : '';
  }

  /* ---------- шаг 1: конспект ---------- */
  function konspekt(o) {
    return 'Ты — опытный преподаватель. Сделай учебный КОНСПЕКТ для подготовки к экзаменам из моих материалов (файлы, фото слайдов, текст или ссылка — после этого сообщения).\n' +
'Если материалов нет, но названы предмет или тема — сделай конспект по своим знаниям на уровне вузовского курса и первым пунктом «Главного» напиши: «Составлено ИИ без материалов лекции — сверьте с лекцией». Если нет ни материалов, ни темы — спроси одной фразой, по какой теме делать.\n' +
'На этом шаге нужен ТОЛЬКО конспект — без вопросов, тестов и карточек (их сделаем потом отдельно).\n' + WISH + '\n\n' +
'ОБЪЁМ: ' + DEPTH[o.depth] + '\n' + LANG[o.lang] + '\n' + SPLIT[o.split] + '\n\n' +
'КАК ПИСАТЬ\n' +
'- Каждая лекция начинается с «#### Суть простыми словами»: 3–5 предложений — о чём лекция и зачем это знать.\n' +
'- Дальше части с подзаголовками «#### …». В каждой: точное определение из материала → объяснение простыми словами → пример.\n' +
'- **Жирным** — ключевые термины, имена, даты, числа (не больше 2–3 в абзаце).\n' +
'- «> Запомни: …» — короткая подсказка или мнемоника; «> Ловушка: …» — где часто ошибаются; «> Пример: …».\n' +
'- Сравнения и классификации — таблицей (до 4 столбцов). Процессы, этапы, причины → следствия — схемой mermaid.\n' +
'- Сохраняй все определения, даты, имена, формулы и списки из материала. Не выдумывай; важное, чего нет в материале, помечай «(дополнительно)».\n' +
'- Формулы — LaTeX: $a^2$ в строке, $$…$$ отдельной строкой. Код — ```cpp … ```. Картинку ссылкой не вставляй: напиши строку [[КАРТИНКА: что изобразить и откуда]].\n' +
'- Короткие абзацы (2–4 предложения), пустая строка между блоками, без длинных строк без пробелов, без HTML и эмодзи.\n\n' +
'ФОРМАТ (символы в начале строк обязательны)\n' +
'# Конспект: <предмет>\n\n' +
'## Лекция 1. <Название>\n' +
'### Главное\n- 4–8 коротких пунктов: самое важное\n' +
'### Конспект\n#### Суть простыми словами\n…\n#### <Подзаголовок>\n…\n' +
'### Термины\nТермин — короткое определение\n\n' +
'ПРИМЕР ОФОРМЛЕНИЯ\n' +
'## Лекция 1. Предмет философии\n### Главное\n- Философия — «любовь к мудрости»; слово ввёл Пифагор.\n### Конспект\n#### Суть простыми словами\nСначала люди объясняли мир **мифами**, потом **верой**, потом **разумом** — так появилась философия.\n\n' +
'#### Типы мировоззрения\n| Тип | На что опирается |\n|---|---|\n| Миф | образы, сказания |\n| Философия | разум, доказательства |\n\n```mermaid\nflowchart LR\n  A[Миф] --> B[Религия]\n  B --> C[Философия]\n```\n\n> Запомни: «фило» — люблю, «софия» — мудрость.\n### Термины\nМировоззрение — система взглядов человека на мир и своё место в нём\n\n' +
'Много материала — по 1–2 лекции за ответ, следующие я попрошу. ' + LONG + '\n' + ONLY;
  }

  /* ---------- шаги 2–5: по конспекту ---------- */
  var R_QS = '- Как спрашивают на экзамене и рубежном контроле: «Что такое…», «Назовите…», «Сравните…», «Почему…», «В чём суть…». Разной сложности: знать, понимать, применять.\n' +
    '- Ответ начинай с «**Коротко:** …» (суть одной фразой), затем 2–5 предложений или список.\n' +
    '- После ответа — «@ Где: …» точный подзаголовок (####) конспекта, где это объяснено.\n';
  var F_QS = '### Вопросы\n? Вопрос\n= **Коротко:** суть. Подробнее…\n@ Где: <подзаголовок>\n';
  var R_TEST = '- У каждого вопроса 4 варианта (если в базе иначе — как в базе). Обычно один верный; если по материалу верных несколько — отметь все.\n' +
    '- Неверные варианты правдоподобные (из той же темы). Без «все ответы верны». Верный — не всегда первый и не самый длинный.\n' +
    '- Проверь каждый верный ответ по материалу — ошибок в ключе быть не должно.\n';
  var F_TEST = '### Тест\n1. Вопрос\n+ верный вариант\n- неверный\n- неверный\n- неверный\n';
  var R_CARDS = '- Одна карточка — один факт: термин, дата, имя, формула или короткий вопрос — и короткий точный ответ (до 15 слов). Самое нужное для экзамена; без повторов.\n';
  var F_CARDS = '### Карточки\nТермин или вопрос — короткий ответ\n';
  var R_TASKS = '- Как на практических занятиях и контрольных: условие полное, с числами и данными; от простых к сложным.\n' +
    '- Решение по шагам, с формулами (LaTeX: $…$, $$…$$); в конце «**Ответ:** …». Для программирования — полный рабочий код (```cpp) и что он выведет (```вывод).\n';
  var F_TASKS = '### Задачи\n?? 1.1 Короткое название\nУсловие\n== Решение по шагам. **Ответ:** …\n';
  var FHEAD = '## Лекция 1. <Название, как в конспекте>\n';

  function qs(o, ctx) {
    return 'Отлично. Теперь по конспекту выше сделай ВОПРОСЫ С ОТВЕТАМИ: ' + how(o.nQs, 'вопросов', '8–15') + ' ' + heads(ctx && ctx.lectures) + '\n' + WISH + '\n\n' +
      R_QS + '\nФОРМАТ\n' + FHEAD + F_QS + '\n' + LONG + '\n' + ONLY + context(o, ctx);
  }
  function bankRules(o) {
    return '- Вопросы моей базы разложи по лекциям по смыслу, текст переноси дословно. Верный в базе может быть отмечен звёздочкой, «+», жирным, ключом или всегда первым — если не видно, определи по материалу.' + (o.testSrc === 'mine' ? ' Своих вопросов не добавляй.' : '') + '\n';
  }
  function bankText(o) { return '\n\n=== МОЯ БАЗА ТЕСТОВ ===\n' + String(o.bank).trim() + '\n=== КОНЕЦ БАЗЫ ==='; }
  function test(o, ctx) {
    var mine = o.testSrc !== 'ai' && String(o.bank || '').trim();
    var what = o.testSrc === 'mine' ? 'из моей базы ниже' : o.testSrc === 'both' ? 'из моей базы ниже, дополнив своими: ' + how(o.nTest, 'вопросов', '10–20') : how(o.nTest, 'вопросов', '10–20');
    return 'Теперь по конспекту выше сделай ТЕСТ — ' + what + ' ' + heads(ctx && ctx.lectures) + '\n' + WISH + '\n\n' +
      R_TEST + (mine ? bankRules(o) : '') + '\nФОРМАТ\n' + FHEAD + F_TEST + '\n' + LONG + '\n' + ONLY + context(o, ctx) + (mine ? bankText(o) : '');
  }
  function cards(o, ctx) {
    return 'Теперь по конспекту выше сделай КАРТОЧКИ для запоминания: ' + how(o.nCards, 'карточек', '10–20') + ' ' + heads(ctx && ctx.lectures) + '\n' + WISH + '\n\n' +
      R_CARDS + '\nФОРМАТ\n' + FHEAD + F_CARDS + '\n' + ONLY + context(o, ctx);
  }
  function tasks(o, ctx) {
    return 'Теперь по конспекту выше сделай ЗАДАЧИ С РЕШЕНИЕМ: ' + how(o.nTasks, 'задач', '3–6') + ' ' + heads(ctx && ctx.lectures) + '\n' + WISH + '\n\n' +
      R_TASKS + '\nФОРМАТ\n' + FHEAD + F_TASKS + '\n' + LONG + '\n' + ONLY + context(o, ctx);
  }
  /* всё сразу: вопросы + тест + карточки (+ задачи, если предмет такой) — для тех, кому лень по шагам */
  function all(o, ctx) {
    var mine = o.testSrc !== 'ai' && String(o.bank || '').trim();
    return 'Отлично. Теперь по конспекту выше сделай всё для подготовки к экзамену — ' + heads(ctx && ctx.lectures) + '\n' + WISH + '\n\n' +
      'ДЛЯ КАЖДОЙ ЛЕКЦИИ ПО ПОРЯДКУ:\n' +
      '1) ВОПРОСЫ С ОТВЕТАМИ — ' + how(o.nQs, 'вопросов', '8–12') + '.\n' + R_QS +
      '2) ТЕСТ — ' + (o.testSrc === 'mine' ? 'из моей базы ниже' : how(o.nTest, 'вопросов', '10–15') + (mine ? ', в том числе из моей базы ниже' : '')) + '.\n' + R_TEST + (mine ? bankRules(o) : '') +
      '3) КАРТОЧКИ — ' + how(o.nCards, 'карточек', '10–15') + '.\n' + R_CARDS +
      '4) ЗАДАЧИ С РЕШЕНИЕМ — только если по этому предмету решают задачи (математика, физика, программирование, экономика, статистика и т. п.): ' + how(o.nTasks, 'задач', '3–5') + '. Если задач по предмету не бывает — раздел «### Задачи» не пиши.\n' + R_TASKS +
      '\nФОРМАТ (для каждой лекции)\n' + FHEAD + F_QS + F_TEST + F_CARDS + F_TASKS +
      '\nПо одной лекции за ответ, если всё не помещается. ' + LONG + '\n' + ONLY + context(o, ctx) + (mine ? bankText(o) : '');
  }
  /* переделать одну лекцию: студент пишет, что не так (или выбирает готовое) — ИИ присылает лекцию целиком */
  function fix(o, ctx) {
    var lec = ctx.lecture || {}, wish = String(ctx.wish || '').trim() || 'проверь и исправь ошибки, дополни то, чего не хватает';
    return 'Переделай лекцию «' + lec.label + '. ' + lec.title + '». Что нужно: ' + wish + '.\n' +
      'Пришли эту лекцию ЦЕЛИКОМ, в том же формате и с теми же разделами (Главное, Конспект, Термины и, если есть, Вопросы, Тест, Карточки, Задачи), заголовок первой строкой — точно так:\n## ' + lec.label + '. ' + lec.title + '\n' +
      'Ничего важного не выкидывай. ' + LONG + '\n' + ONLY +
      '\n\nВОТ ТЕКУЩАЯ ВЕРСИЯ ЛЕКЦИИ:\n<<<\n' + (ctx.source || '') + '\n>>>';
  }

  var STEPS = { konspekt: konspekt, qs: qs, test: test, cards: cards, tasks: tasks, all: all, fix: fix };
  function build(step, o, ctx) { o = cfg(o); return (STEPS[step] || konspekt)(o, ctx || {}); }
  /* «дальше» — когда ответ оборвался */
  function more() { return 'дальше'; }

  SP.NOTES_PROMPTS = { build: build, more: more, defaults: DEF };
})();
